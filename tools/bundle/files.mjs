// The files that exist only inside a bundle: the double-click starter, the
// instructions for Claude Code, and the three lines a recipient reads first.
// Pure string builders, so their content is testable without building anything.

// What travels. `tools/` is deliberately absent - make-setup-code.mjs is the
// operator's, and a recipient holding it gains nothing but a way to be confused.
export const PAYLOAD = ['bin', 'src', 'locales', 'skills', 'docs', 'package.json', 'README.md']

// Inside the payload, paths the recipient has no use for. The plans and specs
// under docs/superpowers are how the tool was built, not how it is used.
export const EXCLUDE = ['docs/superpowers']

const WINDOWS = 'win-x64'

export function starterName (platform) {
  return platform === WINDOWS ? 'START-HIER.cmd' : 'START-HIER.command'
}

function windowsStarter () {
  // %~dp0 is the folder this file sits in, with a trailing backslash. Every
  // path is built from it, so the bundle works from a USB stick or Downloads
  // alike, and nothing is ever looked up on the PATH.
  return `@echo off
rem Generated by make-bundle.mjs. Do not edit.
cd /d "%~dp0"

if not exist "%~dp0runtime\\node\\node.exe" (
  echo Das Paket ist unvollstaendig / this bundle is incomplete.
  echo Bitte das ZIP erneut vollstaendig entpacken / please unzip it again, completely.
  echo.
  pause
  exit /b 1
)

set "GWS_CONNECT_GWS_BIN=%~dp0runtime\\gws\\gws.exe"
"%~dp0runtime\\node\\node.exe" "%~dp0bin\\gws-connect.mjs" %*
echo.
pause
`
}

function macStarter () {
  return `#!/usr/bin/env bash
# Generated by make-bundle.mjs. Do not edit.
# Gatekeeper on the first run: right-click -> Open -> Open.
cd "$(dirname "$0")" || exit 1

if [ ! -x "$PWD/runtime/node/bin/node" ]; then
  echo "Das Paket ist unvollstaendig / this bundle is incomplete."
  echo "Bitte das ZIP erneut vollstaendig entpacken / please unzip it again, completely."
  read -r -p "Enter zum Beenden / Enter to quit "
  exit 1
fi

export GWS_CONNECT_GWS_BIN="$PWD/runtime/gws/gws"
"$PWD/runtime/node/bin/node" ./bin/gws-connect.mjs "$@"
status=$?
echo
read -r -p "Enter zum Beenden / Enter to quit "
exit $status
`
}

export function starter (platform) {
  return platform === WINDOWS ? windowsStarter() : macStarter()
}

export function claudeMd (platform) {
  const win = platform === WINDOWS
  const node = win ? 'runtime\\node\\node.exe' : 'runtime/node/bin/node'
  const gws = win ? 'runtime\\gws\\gws.exe' : 'runtime/gws/gws'
  const starterFile = starterName(platform)
  const trouble = 'docs/de/PROBLEME.md (deutsch) / docs/en/TROUBLESHOOTING.md (English)'
  // The setup prompt needs a keyboard, and you do not have one. Handing the
  // user a window beats handing them an instruction to go find a file.
  const openStarter = win ? 'start "" cmd /c START-HIER.cmd' : 'open START-HIER.command'
  const paste = win
    ? 'right-click pastes in that kind of window, Ctrl+V works on Windows 11'
    : 'Cmd+V'

  return `# gws-connect — instructions for Claude Code

This folder is a self-contained bundle. Everything needed to run is already
here. The user is not technical: they will say something like "run this setup
for me" and expect you to do it.

## Never install anything

Do NOT run \`npm install\`, \`npm install -g\`, \`winget\`, \`brew\`, or any other
installer. Do not install Node. Do not install gws. Both are in this folder
already, and the user may not have the rights to install software at all.

## Use exactly these two paths

- Node: \`${node}\`
- gws: \`${gws}\`

Before running anything, set \`GWS_CONNECT_GWS_BIN\` to the absolute path of the
gws binary above. The double-click starter \`${starterFile}\` does this too — you
can simply run that instead, and it is the better choice when the user wants to
use the tool themselves afterwards.

## What to do

1. Run the doctor first and read what it reports:
   \`${node} bin/gws-connect.mjs doctor\`
2. If the doctor is happy, run the setup:
   \`${node} bin/gws-connect.mjs setup --dialog\`
3. Then add the user's account:
   \`${node} bin/gws-connect.mjs add <address>\`

Add \`--lang de\` or \`--lang en\` to match the language the user is writing in.

## The setup code

Step 2 asks for a setup code. The user received it separately, through a
password manager.

You cannot type it for them, and you must not try: the code is the secret
itself. Never write it to a file, never echo it back, never put it on a command
line or in a log, and never store it anywhere in this folder. If the user pastes
it into the chat instead of the prompt, tell them plainly that it should be
rotated.

A window of its own asks for the code; tell the user to paste it there and
click OK. If the command ends with exit code 3, no window could be shown -
then open the starter in a terminal window instead:

    ${openStarter}

and tell them to paste the code there — ${paste} — and press Enter. Then stay
available: once the code is in, they can come back and you can carry on with
step 3.

If the user moved this folder after connecting accounts, run
\`${node} bin/gws-connect.mjs relink\` once; it repairs the account launchers.

## When something fails

Read ${trouble} before guessing. The doctor's output names the actual problem
in almost every case.
`
}

